// tools/tiled-lua-to-js.mjs
//
// Converts Tiled's Lua map export (tiled/*.lua) into a JS module the
// web build can import (js/levels/*.js). Run it again whenever a map is
// re-exported from Tiled:
//
//   node tools/tiled-lua-to-js.mjs
//
// Lua arrays become ordinary 0-based JS arrays (so layer.data[0] is the
// first tile). Tables that have both positional and named entries keep
// the named entries only if there are no positional ones.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function parseLuaTable(src) {
  let i = 0;
  const ws = () => {
    for (;;) {
      while (i < src.length && /\s/.test(src[i])) i++;
      if (src.startsWith('--', i)) {
        if (src.startsWith('--[[', i)) { const e = src.indexOf(']]', i); i = e < 0 ? src.length : e + 2; }
        else { const e = src.indexOf('\n', i); i = e < 0 ? src.length : e + 1; }
        continue;
      }
      break;
    }
  };
  const expect = (s) => {
    ws();
    if (!src.startsWith(s, i)) throw new Error(`Expected "${s}" at ${i}: ${src.slice(i, i + 40)}`);
    i += s.length;
  };
  const parseString = () => {
    const q = src[i++];
    let out = '';
    while (src[i] !== q) {
      if (src[i] === '\\') {
        i++;
        const c = src[i++];
        if (c === 'n') out += '\n';
        else if (c === 't') out += '\t';
        else if (c === 'r') out += '\r';
        else if (/\d/.test(c)) {
          let num = c;
          while (/\d/.test(src[i]) && num.length < 3) num += src[i++];
          out += String.fromCharCode(Number(num));
        } else out += c;
      } else out += src[i++];
    }
    i++;
    return out;
  };
  const parseValue = () => {
    ws();
    const c = src[i];
    if (c === '{') return parseTable();
    if (c === '"' || c === "'") return parseString();
    if (src.startsWith('true', i)) { i += 4; return true; }
    if (src.startsWith('false', i)) { i += 5; return false; }
    if (src.startsWith('nil', i)) { i += 3; return null; }
    const m = /^-?(0x[0-9a-fA-F]+|\d*\.?\d+(e[-+]?\d+)?)/.exec(src.slice(i, i + 64));
    if (!m) throw new Error(`Unexpected value at ${i}: ${src.slice(i, i + 40)}`);
    i += m[0].length;
    return Number(m[0]);
  };
  const parseTable = () => {
    expect('{');
    const arr = [];
    const obj = {};
    let hasKeys = false;
    for (;;) {
      ws();
      if (src[i] === '}') { i++; break; }
      let key = null;
      if (src[i] === '[') {
        i++;
        key = parseValue();
        expect(']');
        expect('=');
      } else {
        const m = /^[A-Za-z_][A-Za-z0-9_]*/.exec(src.slice(i, i + 128));
        if (m) {
          const save = i;
          i += m[0].length;
          ws();
          if (src[i] === '=' && src[i + 1] !== '=') { i++; key = m[0]; } else i = save;
        }
      }
      const v = parseValue();
      if (key !== null) { obj[key] = v; hasKeys = true; } else arr.push(v);
      ws();
      if (src[i] === ',' || src[i] === ';') i++;
    }
    if (arr.length && !hasKeys) return arr;
    if (!arr.length) return hasKeys ? obj : [];
    // Mixed: keep both (positional under numeric keys from 0).
    arr.forEach((v, k) => { obj[k] = v; });
    return obj;
  };
  ws();
  expect('return');
  return parseValue();
}

const maps = [
  ['tiled/Level1.lua', 'js/levels/Level1.js'],
  ['tiled/Pinball-Level2.lua', 'js/levels/Pinball-Level2.js'],
  // The test map wrapped round the Tiled planet (see CrackedPlanetoid.fromTiledMap).
  ['tiled/Level2.lua', 'js/levels/Level2.js'],
  // Generated by tiled/gen-pinball-curves.js (as Lua) — converted here too.
  ['lua/world/PinballCurveTiles.lua', 'js/world/PinballCurveTiles.js'],
];

for (const [from, to] of maps) {
  const data = parseLuaTable(fs.readFileSync(path.join(root, from), 'utf8'));
  const out = `// ${to} — generated from ${from} by tools/tiled-lua-to-js.mjs. Don't edit by hand.\n` +
    `export default ${JSON.stringify(data)};\n`;
  fs.mkdirSync(path.dirname(path.join(root, to)), { recursive: true });
  fs.writeFileSync(path.join(root, to), out);
  console.log(`${from} -> ${to}`);
}
