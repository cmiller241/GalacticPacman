// tools/gen-asset-list.mjs
//
// Writes js/assetList.js: every image and sound the game loads, so
// love.boot can preload them all before love.load runs (the browser
// can't load files synchronously the way LÖVE does).
//
// Found by scanning js/ for 'img/...' and 'sounds/...' string literals,
// plus the paths built at run time: the button icons
// (img/prompt_<name>.png), the Tiled maps' tileset images, and anything
// in img/sky/. Run with `npm run assets` (npm run build does it too).

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const images = new Set();
const sounds = new Set();

function walk(dir, fn) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, fn);
    else fn(p);
  }
}

const exists = (rel) => fs.existsSync(path.join(root, rel));

walk(path.join(root, 'js'), (file) => {
  if (!file.endsWith('.js') || file.endsWith('assetList.js')) return;
  const src = fs.readFileSync(file, 'utf8');
  for (const m of src.matchAll(/['"`](img\/[^'"`$]+\.(?:png|jpg|jpeg))['"`]/g)) images.add(m[1]);
  for (const m of src.matchAll(/['"`](sounds\/[^'"`$]+\.(?:wav|mp3|ogg))['"`]/g)) sounds.add(m[1]);
  // Tiled tilesets: "image":"../img/foo.png" (relative to tiled/).
  for (const m of src.matchAll(/"image"\s*:\s*"\.\.\/(img\/[^"]+)"/g)) images.add(m[1]);
});

for (const f of fs.readdirSync(path.join(root, 'img'))) {
  if (/^prompt_.*\.png$/.test(f)) images.add('img/' + f);
}
if (exists('img/sky')) {
  for (const f of fs.readdirSync(path.join(root, 'img/sky'))) if (f.endsWith('.png')) images.add('img/sky/' + f);
}

const missing = [...images, ...sounds].filter((p) => !exists(p));
for (const p of missing) {
  console.warn(`gen-asset-list: ${p} is referenced but doesn't exist — left out.`);
  images.delete(p);
  sounds.delete(p);
}

const out = `// js/assetList.js — generated by tools/gen-asset-list.mjs. Don't edit by hand.
export default ${JSON.stringify({ images: [...images].sort(), sounds: [...sounds].sort() }, null, 2)};
`;
fs.writeFileSync(path.join(root, 'js/assetList.js'), out);
console.log(`gen-asset-list: ${images.size} images, ${sounds.size} sounds`);
